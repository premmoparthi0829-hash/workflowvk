// Helper to get initials for avatar
function getCandidateInitials($name) {
    $words = preg_split('/\s+/', trim($name ?: 'VK'));
    $in = '';
    foreach ($words as $w) {
        $clean = preg_replace('/[^A-Za-z]/', '', $w);
        if (!empty($clean)) $in .= strtoupper(substr($clean, 0, 1));
        if (strlen($in) >= 2) break;
    }
    return !empty($in) ? $in : 'VK';
}

function getAvatarColors($name) {
    $palettes = [
        ['bg' => '#e0f2fe', 'color' => '#0284c7'], // Sky
        ['bg' => '#fef3c7', 'color' => '#d97706'], // Amber
        ['bg' => '#dcfce7', 'color' => '#16a34a'], // Emerald
        ['bg' => '#f3e8ff', 'color' => '#9333ea'], // Purple
        ['bg' => '#ffe4e6', 'color' => '#e11d48'], // Rose
        ['bg' => '#e0e7ff', 'color' => '#4f46e5'], // Indigo
        ['bg' => '#ccfbf1', 'color' => '#0d9488'], // Teal
    ];
    $idx = abs(crc32($name ?: 'VK')) % count($palettes);
    return $palettes[$idx];
}

