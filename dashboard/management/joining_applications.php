// Handle Create New Joining Invite (POST)
if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['action']) && $_POST['action'] === 'create_invite') {
    $cand_name = trim($_POST['candidate_name'] ?? '');
    $cand_email = trim($_POST['candidate_email'] ?? '');
    $cand_mobile = trim($_POST['candidate_mobile'] ?? '');
    $cand_desig = trim($_POST['designation'] ?? 'Pickup Associate');
    $cand_dept = !empty($_POST['department_id']) ? intval($_POST['department_id']) : null;
    $validity_days = intval($_POST['validity_days'] ?? 14);
    
    if (empty($cand_name) || empty($cand_mobile) || empty($cand_email)) {
        $flash_msg = "Candidate Name, Email, and Mobile are required.";
        $flash_type = 'danger';
    } else {
        try {
            $yearMonth = date('Ym');
            $stmt = $db->query("SELECT application_no FROM employee_joining_applications WHERE application_no LIKE 'VK-JOIN-{$yearMonth}-%' ORDER BY id DESC LIMIT 1");
            $row = $stmt ? $stmt->fetch(PDO::FETCH_ASSOC) : null;
            $max_num = 0;
            if ($row && !empty($row['application_no']) && preg_match('/-(\d+)$/', $row['application_no'], $m)) {
                $max_num = intval($m[1]);
            }
            $cstmt = $db->query("SELECT COUNT(*) as cnt FROM employee_joining_applications WHERE application_no LIKE 'VK-JOIN-{$yearMonth}-%'");
            $cnt = $cstmt ? ($cstmt->fetch(PDO::FETCH_ASSOC)['cnt'] ?? 0) : 0;
            $next_num = max($max_num, $cnt) + 1;
            
            $db->beginTransaction();
            
            $app_id = null;
            $app_no = null;
            $token = null;
            
            for ($attempt = 0; $attempt < 15; $attempt++) {
                $app_no = sprintf('VK-JOIN-%s-%04d', $yearMonth, $next_num + $attempt);
                $token = bin2hex(random_bytes(24));
                $expires_at = date('Y-m-d H:i:s', strtotime("+{$validity_days} days"));
                try {
                    $stmt = $db->prepare("INSERT INTO employee_joining_applications (
                        application_no, employee_type, token, token_expires_at, status, created_by, created_at
                    ) VALUES (?, 'new_joiner', ?, ?, 'sent_to_employee', ?, NOW())");
                    $stmt->execute([$app_no, $token, $expires_at, $user_id]);
                    $app_id = $db->lastInsertId();
                    break;
                } catch (PDOException $pe) {
                    if ($pe->getCode() == 23000 || strpos($pe->getMessage(), '1062') !== false) {
                        continue;
                    }
                    throw $pe;
                }
            }
            
            if (!$app_id) {
                throw new Exception("Unable to allocate unique application reference number.");
            }
            
            // Pre-populate personal details
            $stmt = $db->prepare("INSERT INTO employee_personal_details (
                application_id, full_name, mobile, email, designation, department_id, father_name, dob, gender, joining_date
            ) VALUES (?, ?, ?, ?, ?, ?, '', CURDATE(), 'male', CURDATE())");
            $stmt->execute([$app_id, $cand_name, $cand_mobile, $cand_email, $cand_desig, $cand_dept]);
            
            // Record status history
            $stmt = $db->prepare("INSERT INTO employee_joining_status_history (
                application_id, from_status, to_status, changed_by_user_id, changed_by_role, remarks
            ) VALUES (?, NULL, 'sent_to_employee', ?, 'management', 'Invite generated by HR')");
            $stmt->execute([$app_id, $user_id]);
            
            $db->commit();
            
            $invite_url = (isset($_SERVER['HTTPS']) && $_SERVER['HTTPS'] === 'on' ? "https" : "http") . "://$_SERVER[HTTP_HOST]/joining_form.php?token={$token}";
            $flash_msg = "New joining application generated successfully! Application Ref: <strong>{$app_no}</strong>. Direct link: <a href='{$invite_url}' target='_blank' class='fw-bold text-decoration-underline'>{$invite_url}</a>";
            $flash_type = 'success';
        } catch (Exception $e) {
            $db->rollBack();
            error_log("Error creating joining application: " . $e->getMessage());
            $flash_msg = "Unable to create joining application invite at this time. Please verify the candidate details and try again.";
            $flash_type = 'danger';
        }
    }
}

