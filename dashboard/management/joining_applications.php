        function copyLink(url) {
            navigator.clipboard.writeText(url).then(function() {
                alert('Candidate application link copied to clipboard!\n\n' + url);
            }).catch(function(err) {
                prompt('Copy this link:', url);
            });
        }

        function switchView(view) {
            const listEl = document.getElementById('listViewContainer');
            const formEl = document.getElementById('formViewContainer');
            const btnList = document.getElementById('btnListView');
            const btnForm = document.getElementById('btnFormView');

            if (view === 'form') {
                listEl.style.display = 'none';
                formEl.style.display = 'block';
                if (btnList && btnForm) {
                    btnList.className = 'btn btn-sm rounded-pill px-3 fw-bold text-muted btn-light';
                    btnForm.className = 'btn btn-sm rounded-pill px-3 fw-bold btn-primary';
                }
                const iframe = document.getElementById('inlineJoiningIframe');
                if (iframe && iframe.contentWindow) {
                    iframe.contentWindow.postMessage({ type: 'vk_request_height' }, '*');
                    try {
                        const doc = iframe.contentDocument || iframe.contentWindow.document;
                        if (doc && doc.body) {
                            const h = Math.max(doc.body.scrollHeight, doc.documentElement.scrollHeight);
                            if (h > 300) iframe.style.height = (h + 40) + 'px';
                        }
                    } catch(e) {}
                }
                window.scrollTo({ top: 120, behavior: 'smooth' });
            } else {
                formEl.style.display = 'none';
                listEl.style.display = 'block';
                if (btnList && btnForm) {
                    btnForm.className = 'btn btn-sm rounded-pill px-3 fw-bold text-muted btn-light';
                    btnList.className = 'btn btn-sm rounded-pill px-3 fw-bold btn-primary';
                }
                window.scrollTo({ top: 120, behavior: 'smooth' });
            }
        }

        function resetBlankForm() {
            const iframe = document.getElementById('inlineJoiningIframe');
            if (iframe) {
                iframe.src = '../../joining_form.php?embedded=1&fresh=' + Date.now();
            }
        }

        // Handle auto-height to eliminate any inside scrollbar
        window.addEventListener('message', function(e) {
            if (e.data && e.data.type === 'vk_resize_joining_iframe') {
                const iframe = document.getElementById('inlineJoiningIframe');
                if (iframe && typeof e.data.height === 'number' && e.data.height > 300) {
                    iframe.style.height = e.data.height + 'px';
                }
            } else if (e.data && e.data.type === 'vk_scroll_parent_top') {
                const formContainer = document.getElementById('formViewContainer');
                if (formContainer && formContainer.style.display !== 'none') {
                    window.scrollTo({ top: 120, behavior: 'smooth' });
                }
            }
        });

        // Direct same-origin iframe height on load
        document.addEventListener('DOMContentLoaded', function() {
            const iframe = document.getElementById('inlineJoiningIframe');
            if (iframe) {
                iframe.addEventListener('load', function() {
                    try {
                        const doc = iframe.contentDocument || iframe.contentWindow.document;
                        if (doc && doc.body) {
                            const h = Math.max(doc.body.scrollHeight, doc.documentElement.scrollHeight);
                            if (h > 300) iframe.style.height = (h + 40) + 'px';
                        }
                    } catch(e) {}
                });
            }

            const params = new URLSearchParams(window.location.search);
            if (params.get('view') === 'form') {
                switchView('form');
            }
        });
